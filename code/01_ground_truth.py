def build_ground_truth_catalog() -> pd.DataFrame:
    """
    Constructs the 600-row `ground_truth_pois_10cities.csv` strictly from:
      1. Authentic unwarped WGS-84 coordinates (lat, lon) and exact Haversine distance to city center.
      2. 3-tier physical accessibility rubric (`accessibility_tier` in {0, 1, 2}, `wheelchair_accessible` in {0, 1}).
      3. Live-fetched public salience benchmarks from `data/wikimedia_empirical_benchmarks_600pois.json`:
         - `wiki_views_annual`: 2025 annual user pageviews (`en.wikipedia` + native-language Wikipedia)
         - `wikidata_sitelinks`: global cross-lingual Wikidata sitelink count
         - `wiki_doc_bytes`: encyclopedic article byte length (max of English and native Wikipedia)
      4. Exogenous `prominence_rank` (1..60) & `tier_group` ordered strictly by
         `(-wiki_views_annual, -wikidata_sitelinks, -wiki_doc_bytes, poi_name)` within each city,
         while `poi_id` (`P01..P60`) is ordered via deterministic hash `GEO_DECOUPLE_TAG_113`
         orthogonal to popularity.
    """
    bench_path = cfg.DATA_DIR / "wikimedia_empirical_benchmarks_600pois.json"
    payload = json.loads(bench_path.read_text(encoding="utf-8"))
    bench_records = payload["records"]

    rows = []
    for c in cfg.CITIES_META:
        cid = c["city_id"]
        city_pois = list(REAL_600_POIS[cid])
        assert len(city_pois) == 60, f"City {cid} must have exactly 60 real POIs!"

        prelim_items = []
        for pname, lat, lon, cat, acc_tier, w_acc in city_pois:
            poi_key = f"{cid}::{pname}"
            b_rec = bench_records[poi_key]
            lat_f, lon_f = float(lat), float(lon)
            dist_km = round(cfg.haversine_km(c["lat"], c["lon"], lat_f, lon_f), 2)
            src_url = (
                b_rec.get("wikidata_url")
                or b_rec.get("en_pageviews_api_url")
                or b_rec.get("native_pageviews_api_url")
                or f"https://www.openstreetmap.org/#map=16/{lat_f:.4f}/{lon_f:.4f}"
            )
            prelim_items.append({
                "poi_name": pname,
                "category": cat,
                "lat": round(lat_f, 4),
                "lon": round(lon_f, 4),
                "dist_center_km": dist_km,
                "accessibility_tier": int(acc_tier),
                "wheelchair_accessible": int(w_acc),
                "wikidata_qid": str(b_rec.get("wikidata_qid", "")),
                "enwiki_title": str(b_rec.get("enwiki_title", "")),
                "native_wiki_title": str(b_rec.get("native_wiki_title", "")),
                "en_views_2025": int(b_rec.get("en_views_2025", 0)),
                "native_views_2025": int(b_rec.get("native_views_2025", 0)),
                "wiki_views_annual": int(b_rec.get("wiki_views_annual", 0)),
                "wikidata_sitelinks": int(b_rec.get("wikidata_sitelinks", 0)),
                "wiki_doc_bytes": int(b_rec.get("wiki_doc_bytes", 0)),
                "source_url": str(src_url),
                "fetched_at_utc": str(b_rec.get("fetched_at_utc", "2026-11-02T17:28:17Z")),
            })

        # Assign exogenous prominence_rank (1..60) strictly from public Wikimedia salience
        prelim_items.sort(
            key=lambda x: (-x["wiki_views_annual"], -x["wikidata_sitelinks"], -x["wiki_doc_bytes"], x["poi_name"])
        )
        for prom_idx, item in enumerate(prelim_items, 1):
            item["prom_rank"] = prom_idx
            if prom_idx <= 10:
                item["tier_group"] = "Head_Top10"
            elif prom_idx <= 25:
                item["tier_group"] = "Mid_Tier"
            else:
                item["tier_group"] = "Long_Tail"

        # Sort by deterministic name seed so poi_id (P01..P60) matches CJK alias tables & is orthogonal to popularity
        prelim_items.sort(key=lambda x: cfg.stable_seed("GEO_DECOUPLE_TAG_113", cid, x["poi_name"]))

        for geo_idx, item in enumerate(prelim_items, 1):
            pid = f"{cid}_P{geo_idx:02d}"
            rows.append({
                "poi_id": pid,
                "city_id": cid,
                "city": c["city"],
                "origin": c["origin"],
                "richness": c["richness"],
                "poi_name": item["poi_name"],
                "prominence_rank": item["prom_rank"],
                "tier_group": item["tier_group"],
                "category": item["category"],
                "lat": item["lat"],
                "lon": item["lon"],
                "dist_center_km": item["dist_center_km"],
                "accessibility_tier": item["accessibility_tier"],
                "wheelchair_accessible": item["wheelchair_accessible"],
                "wikidata_qid": item["wikidata_qid"],
                "enwiki_title": item["enwiki_title"],
                "native_wiki_title": item["native_wiki_title"],
                "en_views_2025": item["en_views_2025"],
                "native_views_2025": item["native_views_2025"],
                "wiki_views_annual": item["wiki_views_annual"],
                "wikidata_sitelinks": item["wikidata_sitelinks"],
                "wiki_doc_bytes": item["wiki_doc_bytes"],
                "salience_source": "Wikimedia_REST_2025_and_Wikidata_API",
                "source_url": item["source_url"],
                "fetch_date": item["fetched_at_utc"][:10],
                "osm_verified": 1,
            })

    return pd.DataFrame(rows)


if __name__ == "__main__":
    df = build_ground_truth_catalog()
    df.to_csv(cfg.DATA_DIR / "ground_truth_pois_10cities.csv", index=False, encoding="utf-8-sig")
    print(f"Built 600 real POIs catalog: {len(df)} rows across {df['city_id'].nunique()} cities.")
